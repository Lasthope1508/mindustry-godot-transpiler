import json
import shutil
import subprocess
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
TURRET_BUILD_STATE = ROOT / 'godot-mindustry/src/game/SourceTurretBuildState.gd'
TURRET_UNIT_HEALTH_PROOF = ROOT / 'godot-mindustry/tools/runtime_proofs/C07TurretUnitHealthProof.gd'


class C07TurretUnitHealthTests(unittest.TestCase):
    def test_c07_turret_unit_health_registration(self):
        generated = ROOT / 'godot-mindustry/src/generated'
        ledger = json.loads((generated / 'source_slice_ledger.json').read_text(encoding='utf-8'))['slices']
        symbols = json.loads((generated / 'source_symbol_registry.json').read_text(encoding='utf-8'))['symbols']
        self.assertEqual(ledger['N2276']['godot_owner'], 'SourceTurretBuildState.source_turret_unit_health_state')
        # TurretBuild.updateTile() syncs its block unit every
        # tick (Turret.java:529-531): `unit.tile(this);` -- and
        # tile() sets up the block stats, second line:
        # `health(tile.health);`
        # (BlockUnitComp.java:22) -- the unit health field
        # (HealthComp.java:11 `float health;`) takes the live
        # tile health. Duo health is 250 at full health
        # (Blocks.java:3319 `health = 250;`, also
        # content_registry_blocks.json blocks/duo/properties/
        # health = 250). N2275 stamped the maxHealth; this
        # slice stamps the one result key: unit_health. The
        # live source is the placed-block health meta
        # (SourcePlacedBlockState.health(sprite)), not a
        # constant: a damaged duo stamps its live health.
        self.assertEqual(
            ledger['N2276']['source_symbols'],
            [
                'source_turret_unit_health_state_result.unit_health',
            ],
        )
        for name in ledger['N2276']['source_symbols']:
            with self.subTest(symbol=name):
                symbol = symbols[name]
                self.assertIn(symbol['java_source'], {
                    'core/src/mindustry/entities/comp/BlockUnitComp.java',
                    'core/src/mindustry/entities/comp/HealthComp.java',
                })
                self.assertEqual(symbol['godot_owner'], 'SourceTurretBuildState.source_turret_unit_health_state')
        self.assertEqual(ledger['N2276']['runtime_proof'], '/root/C07TurretUnitHealthProof')
        self.assertEqual(
            ledger['N2276']['tests'],
            [
                'test_c07_turret_unit_health_registration',
                'test_all_c07_turret_unit_health_input_evidence_is_exact',
                'test_turret_unit_health_state',
                'test_reference_graph_and_actual_c07_turret_unit_health',
            ],
        )
        self.assertTrue(ledger['N2276']['deferred_exprs'])

    def test_all_c07_turret_unit_health_input_evidence_is_exact(self):
        generated = ROOT / 'godot-mindustry/src/generated'
        ledger = json.loads((generated / 'source_slice_ledger.json').read_text(encoding='utf-8'))['slices']
        symbols = json.loads((generated / 'source_symbol_registry.json').read_text(encoding='utf-8'))['symbols']
        for name in ledger['N2276']['source_symbols']:
            with self.subTest(symbol=name):
                symbol = symbols[name]
                self.assertIn(symbol['java_expr'], (ROOT / 'mindustry-upstream' / symbol['java_source']).read_text(encoding='utf-8') if not symbol['java_source'].startswith('arc-core/') else (ROOT / 'arc-upstream' / symbol['java_source']).read_text(encoding='utf-8'))
                self.assertEqual(symbol['godot_owner'], 'SourceTurretBuildState.source_turret_unit_health_state')
        slice_sources = {
            'core/src/mindustry/world/blocks/defense/turrets/Turret.java',
            'core/src/mindustry/entities/comp/BlockUnitComp.java',
            'core/src/mindustry/entities/comp/HealthComp.java',
            'core/src/mindustry/content/Blocks.java',
        }
        upstream = {}
        for source in slice_sources:
            root = ROOT / 'arc-upstream' if source.startswith('arc-core/') else ROOT / 'mindustry-upstream'
            upstream[source] = (root / source).read_text(encoding='utf-8')
        for expr in ledger['N2276']['exact_exprs']:
            with self.subTest(expr=expr):
                self.assertTrue(any(expr in text for text in upstream.values()), expr)

    def test_turret_unit_health_state(self):
        turret = TURRET_BUILD_STATE.read_text(encoding='utf-8')
        # TurretBuild.updateTile() (Turret.java:490-615) syncs
        # its block unit every tick: `unit.tile(this);`
        # (:529) -- and tile() sets up the block stats:
        # `health(tile.health);`
        # (BlockUnitComp.java:22) sets the unit health field
        # (`float health;`,
        # HealthComp.java:11; the float setter is generated by
        # the component annotation processor). Duo health is
        # 250 at full health (Blocks.java:3319 `health = 250;`).
        # The pure function takes the live tile health and
        # returns the one key: `{"unit_health": ..}`. The
        # driver tick reads the live placed-block health
        # (SourcePlacedBlockState.health(sprite) -- the sprite
        # meta `source_block_health`, set to the block health
        # at placement), calls the pure function with it, then
        # stamps the key back on the frame. Java order inside
        # tile() is :21 maxHealth, :22 health, :23 hitSize,
        # :24 set -- so the health tick runs AFTER the N2275
        # maxHealth tick and BEFORE the N2260 unit sync tick
        # (hitSize :23) and the N2274 world position tick
        # (set :24), and BEFORE the aim call, so aim reads a
        # live unit mirror.
        self.assertIn('static func source_turret_unit_health_state(tile_health: float) -> Dictionary:', turret)
        self.assertIn('return {"unit_health": tile_health}', turret)
        self.assertIn('unit.tile(this);', turret)
        self.assertIn('health(tile.health);', turret)
        self.assertIn('float health;', turret)
        self.assertIn('health = 250;', turret)
        # The driver tick lives in the shared TurretBuild driver
        # (SourceTurretBuildState.gd), in the duo branch AFTER
        # the N2275 maxHealth tick and BEFORE the N2260 unit
        # sync tick (Java tile() order :21 maxHealth, :22
        # health, :23 hitSize / :24 set): it reads the live
        # placed-block health off the sprite and stamps the key
        # back on the frame (the default is the duo live value
        # 250.0, full health at placement).
        self.assertIn('var unit_health: Dictionary = source_turret_unit_health_state(source_placed_block_state.health(sprite))', turret)
        self.assertIn('frame["unit_health"] = unit_health.get("unit_health", 250.0)', turret)
        self.assertLess(turret.index('var unit_max_health: Dictionary = source_turret_unit_max_health_state(250.0)'), turret.index('var unit_health: Dictionary = source_turret_unit_health_state(source_placed_block_state.health(sprite))'))
        self.assertLess(turret.index('var unit_health: Dictionary = source_turret_unit_health_state(source_placed_block_state.health(sprite))'), turret.index('var unit_sync: Dictionary'))
        # The proof's keys drive the live health through the pure
        # function and the real driver (the duo health is 250.0
        # at full health / another tile health passes through
        # unchanged / the key is stamped on the frame after the
        # tick / a damaged duo live tick stamps its live 100.0,
        # proving the read is live, not a constant).
        proof = TURRET_UNIT_HEALTH_PROOF.read_text(encoding='utf-8')
        for key in [
            'unit_health_duo',
            'unit_health_other_value',
            'unit_health_stamped_to_frame',
            'unit_health_damaged_live',
        ]:
            with self.subTest(key=key):
                self.assertIn(key, proof)

    def test_reference_graph_and_actual_c07_turret_unit_health(self):
        godot = shutil.which('Godot_v4.6.2-stable_win64_console.exe') or shutil.which('godot')
        self.assertIsNotNone(godot)
        result = subprocess.run([godot, '--headless', '--path', str(ROOT / 'godot-mindustry'), '--scene', 'tools/runtime_proofs/C07TurretUnitHealthProof.tscn', '--quit-after', '300'], capture_output=True, text=True, encoding='utf-8', errors='replace', timeout=180)
        output = result.stdout + result.stderr
        self.assertEqual(result.returncode, 0, output)
        self.assertNotIn('ERROR:', output)
        proofs = [json.loads(line.split(' ', 1)[1]) for line in output.splitlines() if line.startswith('C_07_TURRET_UNIT_HEALTH_PROOF ')]
        self.assertEqual(len(proofs), 1, output)
        self.assertTrue(proofs[0]['matches'], proofs[0])
        for key in [
            'unit_health_duo',
            'unit_health_other_value',
            'unit_health_stamped_to_frame',
            'unit_health_damaged_live',
        ]:
            with self.subTest(key=key):
                self.assertTrue(proofs[0][key], proofs[0])


if __name__ == '__main__':
    unittest.main()
