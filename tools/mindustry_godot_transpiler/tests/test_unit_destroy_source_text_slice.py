def test_unit_destroy_effect_literals_have_one_source_text_owner():
    owner = (GAME / "SourceUnitDestroySourceTextState.gd").read_text(encoding="utf-8")
    effects = (GAME / "SourceUnitDestroyEffectsState.gd").read_text(encoding="utf-8")

    assert "class_name SourceUnitDestroySourceTextState" in owner
    assert 'const source_unit_destroy_source_text_state := preload("res://src/game/SourceUnitDestroySourceTextState.gd")' in effects
    for name in RAW_UNIT_DESTROY_CONSTANTS:
        assert f"const {name} := \"" in owner
        assert f"const {name} := source_unit_destroy_source_text_state.{name}" in effects
        assert f"const {name} := \"" not in effects
