"""Register the Turret unit live health (N2276).

TurretBuild.updateTile (Turret.java:490-615) syncs its block
unit every tick: `unit.tile(this);` (Turret.java:529) -- and
tile() sets up the block stats, second line:
`health(tile.health);` (BlockUnitComp.java:22) sets the unit
health field (`float health;`, HealthComp.java:11; the float
setter is generated by the component annotation processor).
Duo health is 250 at full health (Blocks.java:3319
`health = 250;`, also content_registry_blocks.json
blocks/duo/properties/health = 250). N2275 stamped the
maxHealth; the frame still had no unit health, so reads of
the unit's health (healthf(), damaged(), heal()) had nothing
live. This slice adds the one pure function on the shared
TurretBuild driver file plus one driver tick in the duo
branch AFTER the N2275 maxHealth tick and BEFORE the N2260
unit sync tick (Java tile() order :21 maxHealth, :22 health,
:23 hitSize, :24 set).

GREEN decisions (pinned by this slice): (1) One pure function
on SourceTurretBuildState.gd,
source_turret_unit_health_state(tile_health), returning
`{"unit_health": ..}` -- the live tile health passed in,
verbatim (no formula: health is a plain field assignment).
Plus one driver tick in the duo branch (immediately after
the N2275 maxHealth tick, before the N2260 unit sync tick)
that reads the live placed-block health via
SourcePlacedBlockState.health(sprite) -- the sprite meta
`source_block_health`, set to the block health at placement
(SourcePlacedBlockState.initialize_sprite) -- and stamps the
key back on the frame. The stamp default is the duo live
value 250.0 (full health at placement). The tick runs BEFORE
the aim call, so aim reads a live unit mirror (Java :529-531
runs before :601/:609). (2) `250.0` is NOT in exact_exprs
(the duo health lives in Blocks.java, pinned by
`health = 250;` in exact_exprs plus an assert on the .gd text
in the test, same rule as N2275's `250.0`). (3) The live
source is the placed-block health meta, which already
exists -- no new frame input is invented, and no value is
fabricated: a damaged duo stamps its live health. (4) No
legacy `source_turret_unit_health_result` schema exists, so
the contract validator falls through to the new
source_turret_unit_health_state_result schema and no alias
is needed. SSOT expected after GREEN: symbols +1, Done +1,
contracts +1, schema +2, 11651/1725/1659/3109 ->
11652/1726/1660/3111; defense shard slices 202 -> 203,
contracts 201 -> 202.
"""
import json
import sys
from pathlib import Path

from mindustry_port import source_ssot, source_symbols
from register_c07_turret_unit_max_health import DEFERRED as N2275_DEFERRED
from register_liquid_consumer_hydration import backed

ROOT = Path(__file__).resolve().parents[2]
GODOT = ROOT / 'godot-mindustry'
TURRET = 'core/src/mindustry/world/blocks/defense/turrets/Turret.java'
BLOCK_UNIT = 'core/src/mindustry/entities/comp/BlockUnitComp.java'
HEALTH_COMP = 'core/src/mindustry/entities/comp/HealthComp.java'
BLOCKS = 'core/src/mindustry/content/Blocks.java'
PROOF = '/root/C07TurretUnitHealthProof'
UNIT_HEALTH_OWNER = 'SourceTurretBuildState.source_turret_unit_health_state'
TESTS = ['test_c07_turret_unit_health_registration', 'test_all_c07_turret_unit_health_input_evidence_is_exact', 'test_turret_unit_health_state', 'test_reference_graph_and_actual_c07_turret_unit_health']
# The slice sources the N2276 test checks exact_exprs
# against -- every expr in EXACT_EXPRS below must appear verbatim
# in one of these files.
SLICE_SOURCES = [
    'core/src/mindustry/world/blocks/defense/turrets/Turret.java',
    'core/src/mindustry/entities/comp/BlockUnitComp.java',
    'core/src/mindustry/entities/comp/HealthComp.java',
    'core/src/mindustry/content/Blocks.java',
]
EXACT_EXPRS = ['unit.tile(this);', 'health(tile.health);', 'float health;', 'health = 250;']

# DEFERRED is carried from the N2275 register script via import --
# never retyped. The unit live health is done by this slice, so the
# N2275 "unit live health re-sync" entry is superseded; the
# cross-tick queuedBullets counter, effects/sound, findTarget /
# the other ItemTurret defs still wait.
DEFERRED = list(N2275_DEFERRED) + [
    'Turret unit live health from tile() (BlockUnitComp.tile() `health(tile.health);`, BlockUnitComp.java:22 -> HealthComp health field, HealthComp.java:11) -- DONE by this slice (N2276); the duo driver reads the live placed-block health via SourcePlacedBlockState.health(sprite) (sprite meta `source_block_health`, set to the block health at placement) and stamps unit_health on the frame right after the N2275 maxHealth tick. tile() is now fully covered for duo (:21 maxHealth N2275, :22 health N2276, :23 hitSize N2260, :24 set N2274).',
    'Turret unit live health for defs other than duo -- the pure function takes tile_health as a param; only duo is wired in the driver (live placed-block health, default 250.0).',
]


def definitions():
    def a(typ, expr, rule, source=TURRET, **extra):
        return backed(typ, source, expr, rule, **extra)

    unit_health_inputs = {
        'tile_health': a('float', 'tile.health', 'The live tile health feeding the unit health (BlockUnitComp.java:22; duo health is 250 at full health, Blocks.java:3319 `health = 250;`, also content_registry_blocks.json blocks/duo/properties/health = 250; read live from the placed-block health meta, SourcePlacedBlockState.health(sprite)).', source=BLOCK_UNIT),
    }
    unit_health_outputs = {
        'unit_health': a('float', 'health(tile.health);', 'The unit health after the tick (BlockUnitComp.java:22 -- health(tile.health) sets the HealthComp health field, HealthComp.java:11; 250.0 live for a full-health duo, lower when damaged).', source=BLOCK_UNIT),
    }
    return unit_health_inputs, unit_health_outputs


def verify():
    """Check every EXACT_EXPRS line and every input/output
    java_expr appears verbatim in its upstream source, without
    touching any SSOT JSON. Exit 0 when all are present."""
    upstream = {}
    for source in SLICE_SOURCES:
        upstream_root = ROOT / 'arc-upstream' if source.startswith('arc-core/') else ROOT / 'mindustry-upstream'
        upstream[source] = (upstream_root / source).read_text(encoding='utf-8')
    missing = []
    for expr in EXACT_EXPRS:
        if not any(expr in text for text in upstream.values()):
            missing.append(expr)
    inputs_outputs = definitions()
    total = len(EXACT_EXPRS)
    for keys in inputs_outputs:
        total += len(keys)
        for field, meta in keys.items():
            source = meta['java_source']
            upstream_root = ROOT / 'arc-upstream' if source.startswith('arc-core/') else ROOT / 'mindustry-upstream'
            text = (upstream_root / source).read_text(encoding='utf-8')
            if meta['java_expr'] not in text:
                missing.append('%s: %s' % (field, meta['java_expr']))
    if missing:
        for expr in missing:
            print('MISSING: %s' % expr)
        print('%d/%d exprs present' % (total - len(missing), total))
        return 1
    print('%d/%d exprs present' % (total, total))
    return 0


def main():
    symbols = {}
    unit_health_inputs, unit_health_outputs = definitions()

    entries = [
        ('N2276', UNIT_HEALTH_OWNER, 'source_turret_unit_health_state', TURRET, 'mindustry.world.blocks.defense.turrets.Turret.TurretBuild', 'TurretBuild.updateTile()', unit_health_inputs, unit_health_outputs, True, 'Dictionary'),
    ]
    all_names = []
    for sid, owner, prefix, source, cls, method, inputs, outputs, has_contract, return_type in entries:
        names = []
        for suffix, keys in [('input', inputs), ('result', outputs)]:
            name = prefix + '_' + suffix
            for field, meta in keys.items():
                meta['used_by'] = [owner]
                if suffix == 'result':
                    symbol = name + '.' + field
                    names.append(symbol)
                    symbols[symbol] = dict(status='source-backed', godot_owner=owner, godot_symbol=symbol, java_source=meta['java_source'], java_method=method, java_expr=meta['java_expr'], rule=meta['rule'], tests=TESTS, runtime_proof=PROOF)
            source_symbols.upsert_source_state_schema(GODOT, name, dict(status='active', owner=owner, source_slice=sid, keys=keys, runtime_proof=PROOF, rule='Source-backed Turret unit live health from BlockUnitComp.tile() / HealthComp.'))
        if has_contract:
            source_symbols.upsert_source_api_contract(GODOT, owner, dict(status='active', source_slice=sid, java_source=source, source_method=method, params=[dict(name=k, type=v['type'], schema=prefix + '_input.' + k) for k, v in inputs.items()], return_type=return_type, return_keys=list(outputs), tests=TESTS, runtime_proof=PROOF, rule='Source-backed Turret unit live health from BlockUnitComp.tile() / HealthComp.'))
        all_names.extend(names)

    by_slice = {}
    # The test pins this order: unit_health.
    by_slice['N2276'] = [
        'source_turret_unit_health_state_result.unit_health',
    ]
    source_symbols.upsert_source_slice(GODOT, 'N2276', dict(status='done', java_source=TURRET, java_class='mindustry.world.blocks.defense.turrets.Turret.TurretBuild', java_method='TurretBuild.updateTile()', godot_owner=UNIT_HEALTH_OWNER, exact_exprs=EXACT_EXPRS, source_symbols=by_slice['N2276'], tests=TESTS, runtime_proof=PROOF, deferred_exprs=DEFERRED))

    source_symbols.upsert_source_symbols(GODOT, symbols)
    source_symbols.write_source_symbol_audit_report(GODOT)

    manifest = json.loads((GODOT / 'src/generated/source_ssot_modules.json').read_text(encoding='utf-8'))
    modules = manifest['modules']
    new_owners = {definition[1] for definition in entries}
    for name, module in modules.items():
        if module.get('canonical_module') == 'api_contracts':
            selected = source_ssot.build_extension_shard(GODOT, name)[module['root_key']]
            if new_owners.intersection(selected):
                optional = module.setdefault('optional_mirror_fields', [])
                if 'return_type' not in optional:
                    optional.append('return_type')
    source_ssot.write_registered_json(GODOT, 'module_manifest', manifest)
    for canonical in ['slice_ledger', 'api_contracts', 'state_schema', 'registry', 'audit_report', 'module_manifest']:
        for name, module in modules.items():
            if module.get('canonical_module') == canonical:
                source_ssot.write_registered_json(GODOT, name, source_ssot.build_extension_shard(GODOT, name))


if __name__ == '__main__':
    if '--verify' in sys.argv:
        sys.exit(verify())
    main()
